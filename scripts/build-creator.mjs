// Inlines three.js into web/creator.html so the avatar renderer works fully offline
// (no CDN), then writes:
//   web/dist/creator.html          – standalone page (open in a browser to test)
//   src/creator/creatorHtml.ts     – the same page as a string for <WebView source={{ html }} />
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
// three's "exports" map hides package.json, so resolve the main entry (build/three.cjs).
const threeBuild = dirname(require.resolve('three'))
const three = readFileSync(join(threeBuild, 'three.min.js'), 'utf8')
const page = readFileSync(join(root, 'web', 'creator.html'), 'utf8')

if (!page.includes('<!--THREE-->')) throw new Error('creator.html is missing the <!--THREE--> placeholder')
// Function replacer so `$` sequences inside three.js are not treated as patterns.
const html = page.replace('<!--THREE-->', () => `<script>${three.replace(/<\/script/gi, '<\\/script')}</script>`)

mkdirSync(join(root, 'web', 'dist'), { recursive: true })
writeFileSync(join(root, 'web', 'dist', 'creator.html'), html)
mkdirSync(join(root, 'src', 'creator'), { recursive: true })
writeFileSync(
  join(root, 'src', 'creator', 'creatorHtml.ts'),
  '// GENERATED by scripts/build-creator.mjs – edit web/creator.html instead.\n' +
    `export const CREATOR_HTML: string = ${JSON.stringify(html)}\n`
)
console.log(`creator built: ${(html.length / 1024).toFixed(0)} KB`)
